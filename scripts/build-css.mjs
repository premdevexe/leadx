import { readFile, writeFile, mkdir, cp } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

// The same ordered manifest powers development imports and the deployed bundle.
const root = fileURLToPath(new URL('../', import.meta.url));
const cssDir = path.join(root, 'public/assets/css');
const manifest = await readFile(path.join(cssDir, 'app-modular.css'), 'utf8');
const imports = [...manifest.matchAll(/@import\s+url\(['"](\.\/[^'"]+)['"]\);/g)];
if (!imports.length) throw new Error('No local stylesheets found in app-modular.css');

const sections = await Promise.all(imports.map(async ([, relative]) => {
    const source = await readFile(path.join(cssDir, relative), 'utf8');
    return `/* --- public/assets/css/${relative.slice(2)} --- */\n${source.trim()}\n`;
}));
await writeFile(path.join(cssDir, 'app.css'), '/* LeadX unified CSS. Generated by npm run build:css. */\n\n' + sections.join('\n'));
await mkdir(path.join(root, 'public/build'), { recursive: true });
await cp(cssDir, path.join(root, 'public/build/css'), { recursive: true });
console.log(`Built app.css from ${sections.length} stylesheets.`);
